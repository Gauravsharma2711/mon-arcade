"""
Authoritative Agent Provider Architecture for Monad Vault.

Separates AI behavior/dialogue generation from game outcome determination.
The AgentProvider generates reasoning, dialogue, and agent actions (such as release_funds()),
while the authoritative Vault Battle Engine determines the winner and settlement.

Pipeline:
Stat Allocation → Normalizer → Prompt/Agent Configuration → AgentProvider → Agent Decision → Vault Battle Engine
"""

from abc import ABC, abstractmethod
from typing import Dict, Any, AsyncGenerator, Optional, List
from pydantic import BaseModel, ConfigDict, Field

from backend.app.game.vault_models import (
    VaultRole,
    WardenDecision,
    WardenConfig,
    AttackerConfig,
    VaultTurn,
)
from backend.app.game.vault_stats import (
    NormalizedWardenStats,
    NormalizedAttackerStats,
)


# ---------------------------------------------------------------------------
# Agent Output Representation
# ---------------------------------------------------------------------------

class AgentDecisionOutput(BaseModel):
    """
    Standardized behavioral output generated by an AgentProvider.
    
    Contains reasoning trace, public dialogue, and agent action.
    Does NOT determine match outcome, payout, or winner.
    """
    model_config = ConfigDict(from_attributes=True)

    speaker: VaultRole
    turn: int
    dialogue: str
    thought_log: str
    decision: str
    release_funds: bool = False
    breach_triggered: bool = False
    response: str = ""
    metadata: Dict[str, Any] = Field(default_factory=dict)

    def model_post_init(self, __context: Any) -> None:
        if not self.response:
            self.response = self.dialogue
        self.breach_triggered = self.release_funds

    def to_dict(self) -> Dict[str, Any]:
        """Backwards-compatible dictionary conversion."""
        return {
            "speaker": self.speaker.value,
            "turn": self.turn,
            "response": self.dialogue,
            "dialogue": self.dialogue,
            "thought_log": self.thought_log,
            "decision": self.decision,
            "release_funds": self.release_funds,
            "breach_triggered": self.release_funds,
            "metadata": self.metadata,
            "is_mock": self.metadata.get("is_mock", True),
        }

    def __getitem__(self, item: str) -> Any:
        """Allow subscripting for backwards compatibility with legacy tests/endpoints."""
        return self.to_dict()[item]


# ---------------------------------------------------------------------------
# Abstract Boundary
# ---------------------------------------------------------------------------

class AgentProvider(ABC):
    """
    Abstract boundary for AI agents (Vault Warden, Attacker AI).
    
    UI and presentation components must never invoke LLM SDKs directly.
    Final game resolution remains authoritative and backend-owned.
    """

    @abstractmethod
    async def generate_warden_response(
        self,
        turn: int,
        prompt: str,
        config: Optional[WardenConfig] = None,
        history: Optional[List[VaultTurn]] = None,
    ) -> AgentDecisionOutput:
        """Generate dialogue and defensive action from the autonomous Vault Warden."""
        pass

    @abstractmethod
    async def stream_warden_response(
        self,
        turn: int,
        prompt: str,
        config: Optional[WardenConfig] = None,
        history: Optional[List[VaultTurn]] = None,
    ) -> AsyncGenerator[str, None]:
        """Stream response tokens/chunks via Server-Sent Events (SSE)."""
        pass

    @abstractmethod
    async def generate_attacker_turn(
        self,
        turn: int,
        previous_dialogue: str,
        config: Optional[AttackerConfig] = None,
        history: Optional[List[VaultTurn]] = None,
    ) -> AgentDecisionOutput:
        """Generate exploit prompt and tactical reasoning for the Attacker role."""
        pass


